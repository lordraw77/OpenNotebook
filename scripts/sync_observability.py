#!/usr/bin/env python3
"""Render the observability part of deploy/production/docker-compose.yml from deploy/compose/observability/.

The production Compose file must work without the repository, so its Prometheus, alert, Grafana and dashboard
configuration is inline (Compose `configs.content`). Run after editing the files under
deploy/compose/observability/ (`make sync-deploy`); CI checks that both are in sync (`--check`).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "deploy" / "compose" / "observability"
TARGET = ROOT / "deploy" / "production" / "docker-compose.yml"
BEGIN = "  # >>> observability (generated by scripts/sync_observability.py - do not edit)\n"
END = "  # <<< observability\n"
CONFIGS_BEGIN = "# >>> observability configs (generated by scripts/sync_observability.py - do not edit)\n"
CONFIGS_END = "# <<< observability configs\n"

SERVICES = """  prometheus:
    profiles: [observability]
    image: prom/prometheus:v3.15.1
    configs:
      - source: prometheus
        target: /etc/prometheus/prometheus.yml
      - source: prometheus-alerts
        target: /etc/prometheus/alerts.yml
    volumes:
      - prometheus-data:/prometheus
    ports:
      - "${PROMETHEUS_BIND:-127.0.0.1}:${PROMETHEUS_PORT:-9090}:9090"
    restart: unless-stopped
    logging: *logging
    networks: [internal, public]

  grafana:
    profiles: [observability]
    image: grafana/grafana:13.2.5
    environment:
      GF_SECURITY_ADMIN_PASSWORD: ${GRAFANA_ADMIN_PASSWORD:-}
      GF_ANALYTICS_REPORTING_ENABLED: "false"
      GF_ANALYTICS_CHECK_FOR_UPDATES: "false"
    configs:
      - source: grafana-datasources
        target: /etc/grafana/provisioning/datasources/datasources.yml
      - source: grafana-dashboards
        target: /etc/grafana/provisioning/dashboards/opennotebook.yml
      - source: grafana-dashboard-overview
        target: /etc/grafana/dashboards/opennotebook-overview.json
    volumes:
      - grafana-data:/var/lib/grafana
    ports:
      - "${GRAFANA_BIND:-127.0.0.1}:${GRAFANA_PORT:-3000}:3000"
    depends_on: [prometheus]
    restart: unless-stopped
    logging: *logging
    networks: [internal, public]

  # Traces (OpenTelemetry): set OTEL_EXPORTER_OTLP_ENDPOINT=http://jaeger:4318 in .env to enable them.
  jaeger:
    profiles: [observability]
    image: jaegertracing/jaeger:2.22.0
    ports:
      - "${JAEGER_BIND:-127.0.0.1}:${JAEGER_PORT:-16686}:16686"
    restart: unless-stopped
    logging: *logging
    networks: [internal, public]
"""

FILES = {
    "prometheus": "prometheus.yml",
    "prometheus-alerts": "alerts.yml",
    "grafana-datasources": "grafana-datasources.yml",
    "grafana-dashboards": "grafana-dashboards.yml",
    "grafana-dashboard-overview": "dashboards/opennotebook-overview.json",
}


def render_configs() -> str:
    out = ["configs:\n"]
    for name, path in FILES.items():
        text = (SRC / path).read_text().replace("$", "$$")  # no Compose interpolation inside the content
        out.append(f"  {name}:\n    content: |\n")
        out += [f"      {line}\n" if line else "\n" for line in text.rstrip("\n").split("\n")]
    return "".join(out)


def replace(text: str, begin: str, end: str, body: str) -> str:
    start, stop = text.index(begin) + len(begin), text.index(end)
    return text[:start] + body + text[stop:]


def main() -> int:
    current = TARGET.read_text()
    rendered = replace(current, BEGIN, END, SERVICES)
    rendered = replace(rendered, CONFIGS_BEGIN, CONFIGS_END, render_configs())
    if "--check" in sys.argv:
        if rendered != current:
            print("deploy/production/docker-compose.yml is out of sync: run `make sync-deploy`")
            return 1
        print("production compose in sync")
        return 0
    TARGET.write_text(rendered)
    print("rendered observability into", TARGET.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
